-- #8 수수료 검증: 채널별 수수료율을 '규칙 = 데이터' 원칙(설계원칙 1)에 따라 테이블로 둔다.
-- #2 는 "명세 합 = 원장"을 기대했지만 실제 정산은 플랫폼이 수수료를 떼고 준다.
-- 진짜 기대값은 "원장 − 수수료"이고, 요율은 채널마다 다르므로 코드가 아니라 여기에 있다.

create table fee_rule (
    channel varchar(64)  not null primary key,   -- 채널당 한 행. 정액·혼합·시점별 요율은 범위 밖(파생 이슈).
    -- 비율로 저장한다: 0.033 = 3.3%.  퍼센트(3.3)로 두면 계산식마다 /100 이 붙고,
    -- 한 군데만 빠뜨려도 100배 오차가 조용히 난다.
    -- scale 6 = 0.028750 같은 세밀한 협의 요율까지 수용(4자리면 잘려서 전 건 오차가 된다).
    rate    numeric(9,6) not null,
    constraint ck_fee_rule_rate_range check (rate >= 0 and rate < 1)
);

-- 규칙이 없는 채널은 행이 없어도 된다 — 검출 쿼리가 left join + coalesce(rate, 0) 로 읽는다.
-- inner join 이면 규칙 누락이 '검출 0건'으로 보여 오차가 조용히 묻힌다(대사에서 가장 위험한 실패).
